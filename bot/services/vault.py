def get_vault_response(text: str) -> str:
    """Генерує миттєву автентичну відповідь Мопса, якщо AI тимчасово недоступний."""
    t = text.lower()
    if any(w in t for w in ["здоров", "привіт", "вечір", "салам", "вечер", "хай"]):
        return random.choice(VAULT_GREETINGS)
    if any(w in t for w in ["чепуха", "петух", "чорт", "смердючий", "лох", "дурак", "пес", "пёс", "гребень"]):
        return random.choice(VAULT_ROASTS)
    if any(w in t for w in ["шо думаєш", "як", "чому", "поясни", "хто", "де", "коли", "?"]):
        return random.choice(VAULT_QUESTIONS)
    return random.choice(VAULT_GENERAL)
