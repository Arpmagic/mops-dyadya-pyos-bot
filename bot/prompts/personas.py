def get_role_prompt(role_key: str, user_text: str = "") -> str:
    persona = PERSONAS.get(role_key, PERSONAS["mops"])
    base_prompt = persona["prompt"]
    
    ut = user_text.lower()
    
    # RAG-lite: Dynamically inject challenges lore
    challenge_keywords = ["лось", "муха", "черепаха", "пилосос", "пылесос", "лящ", "фанер", "шокер", "травмат", "чифір", "чифир"]
    if any(k in ut for k in challenge_keywords):
        base_prompt += "\n" + CHALLENGES_LORE
        
    # RAG-lite: Dynamically inject links lore
    link_keywords = ["відео", "видос", "ссылк", "история", "вася", "васю", "золотая", "кость", "бердичев", "бердичів"]
    if any(k in ut for k in link_keywords):
        base_prompt += "\n" + LINKS_LORE
        
    # Inject dynamic mood
    if role_key == "mops":
        mood = random.choice(MOPS_MOODS)
        base_prompt += f"\n\n🚨 ТВІЙ ПОТОЧНИЙ НАСТРІЙ: {mood} 🚨\nВідповідай суворо в цьому настрої, але не кажи про нього прямо."
        
    return base_prompt

